package com.musicplayer.lytrix.innertube.models.body

import kotlinx.serialization.Serializable
import com.musicplayer.lytrix.innertube.models.Context

@Serializable
data class LikeBody(
    val context: Context,
    val target: Target,
) {
    @Serializable
    sealed class Target {
        @Serializable
        data class VideoTarget(
            val videoId: String,
        ) : Target()

        @Serializable
        data class PlaylistTarget(
            val playlistId: String,
        ) : Target()
    }
}
