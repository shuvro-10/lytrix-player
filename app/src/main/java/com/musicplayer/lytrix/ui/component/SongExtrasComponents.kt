@Composable
fun YouTubeCommentsSheet(
    videoId: String,
    songTitle: String,
    accentColor: Color,
    onDismiss: () -> Unit
) {
    val context = LocalContext.current
    val clipboard = LocalClipboardManager.current
    val scope = rememberCoroutineScope()

    var isLoading by remember(videoId) { mutableStateOf(true) }
    var isLoadingMore by remember(videoId) { mutableStateOf(false) }
    var countText by remember(videoId) { mutableStateOf<String?>(null) }
    var comments by remember(videoId) { mutableStateOf<List<YouTubeCommentItem>>(emptyList()) }
    var nextToken by remember(videoId) { mutableStateOf<String?>(null) }
    var useWebClient by remember(videoId) { mutableStateOf(false) }
    var errorMessage by remember(videoId) { mutableStateOf<String?>(null) }

    val repliesMap = remember(videoId) { mutableStateMapOf<String, List<YouTubeCommentItem>>() }
    val loadingRepliesIds = remember(videoId) { mutableStateMapOf<String, Boolean>() }

    LaunchedEffect(videoId) {
        isLoading = true
        errorMessage = null
        val res = withContext(Dispatchers.IO) { YouTube.comments(videoId) }
        res.onSuccess { page ->
            if (page == null) {
                comments = emptyList()
                countText = null
            } else {
                countText = page.countText ?: page.countShort
                comments = page.comments
                nextToken = page.nextToken
                useWebClient = page.useWebClient
            }
        }.onFailure { err ->
            errorMessage = err.message ?: "Failed to load comments"
        }
        isLoading = false
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 16.dp, vertical = 12.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(onClick = onDismiss) {
                Icon(
                    imageVector = Icons.AutoMirrored.Rounded.ArrowBack,
                    contentDescription = "Back",
                    tint = Color.White
                )
            }
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = countText ?: "Comments",
                    fontSize = 19.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.White,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
                Text(
                    text = songTitle,
                    fontSize = 12.sp,
                    color = Color.White.copy(alpha = 0.6f),
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
            }
        }

        HorizontalDivider(color = Color.White.copy(alpha = 0.08f))

        when {
            isLoading -> {
                Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                    LytrixExpressiveSpinner(color = accentColor, size = 38.dp)
                }
            }
            errorMessage != null -> {
                Box(
                    modifier = Modifier.fillMaxSize().padding(24.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = errorMessage ?: "Unable to fetch comments",
                        color = MaterialTheme.colorScheme.error
                    )
                }
            }
            comments.isEmpty() -> {
                Box(
                    modifier = Modifier.fillMaxSize().padding(24.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Icon(
                            imageVector = Icons.Rounded.CommentsDisabled,
                            contentDescription = null,
                            tint = Color.White.copy(alpha = 0.45f),
                            modifier = Modifier.size(44.dp)
                        )
                        Spacer(modifier = Modifier.height(10.dp))
                        Text(
                            text = "No comments available for this track",
                            color = Color.White.copy(alpha = 0.7f),
                            fontSize = 14.sp
                        )
                    }
                }
            }
            else -> {
                LazyColumn(
                    modifier = Modifier.fillMaxSize(),
                    contentPadding = PaddingValues(16.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    items(comments, key = { it.id }) { comment ->
                        val loadedReplies = repliesMap[comment.id]
                        val isLoadingReply = loadingRepliesIds[comment.id] == true

                        Surface(
                            shape = RoundedCornerShape(16.dp),
                            color = Color.White.copy(alpha = 0.06f),
                            modifier = Modifier
                                .fillMaxWidth()
                                .clickable {
                                    clipboard.setText(AnnotatedString(comment.text))
                                    Toast.makeText(context, "Comment copied", Toast.LENGTH_SHORT).show()
                                }
                        ) {
                            Column(modifier = Modifier.padding(14.dp)) {
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    AsyncImage(
                                        model = comment.authorAvatar,
                                        contentDescription = comment.author,
                                        contentScale = ContentScale.Crop,
                                        modifier = Modifier
                                            .size(32.dp)
                                            .clip(CircleShape)
                                            .background(Color.White.copy(alpha = 0.1f))
                                    )
                                    Spacer(modifier = Modifier.width(10.dp))
                                    Column(modifier = Modifier.weight(1f)) {
                                        Row(
                                            verticalAlignment = Alignment.CenterVertically,
                                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                                        ) {
                                            Text(
                                                text = comment.author.ifBlank { "YouTube User" },
                                                fontSize = 13.sp,
                                                fontWeight = FontWeight.SemiBold,
                                                color = if (comment.isCreator) accentColor else Color.White,
                                                maxLines = 1,
                                                overflow = TextOverflow.Ellipsis
                                            )
                                            if (comment.isPinned) {
                                                Icon(
                                                    imageVector = Icons.Rounded.PushPin,
                                                    contentDescription = "Pinned",
                                                    tint = accentColor,
                                                    modifier = Modifier.size(13.dp)
                                                )
                                            }
                                            if (comment.isHearted) {
                                                Icon(
                                                    imageVector = Icons.Rounded.Favorite,
                                                    contentDescription = "Hearted by creator",
                                                    tint = Color(0xFFFF4D6D),
                                                    modifier = Modifier.size(13.dp)
                                                )
                                            }
                                        }
                                        if (comment.publishedTime.isNotBlank()) {
                                            Text(
                                                text = comment.publishedTime,
                                                fontSize = 11.sp,
                                                color = Color.White.copy(alpha = 0.5f)
                                            )
                                        }
                                    }
                                    if (comment.likeCount.isNotBlank() && comment.likeCount != "0") {
                                        Row(verticalAlignment = Alignment.CenterVertically) {
                                            Icon(
                                                imageVector = Icons.Rounded.ThumbUp,
                                                contentDescription = null,
                                                tint = Color.White.copy(alpha = 0.55f),
                                                modifier = Modifier.size(13.dp)
                                            )
                                            Spacer(modifier = Modifier.width(4.dp))
                                            Text(
                                                text = comment.likeCount,
                                                fontSize = 11.5.sp,
                                                color = Color.White.copy(alpha = 0.65f)
                                            )
                                        }
                                    }
                                }

                                Spacer(modifier = Modifier.height(8.dp))
                                Text(
                                    text = comment.text,
                                    fontSize = 13.5.sp,
                                    color = Color.White.copy(alpha = 0.92f),
                                    lineHeight = 19.sp
                                )

                                if (comment.repliesToken != null && !comment.repliesLabel.isNullOrBlank()) {
                                    Spacer(modifier = Modifier.height(8.dp))
                                    Text(
                                        text = when {
                                            isLoadingReply -> "Loading replies..."
                                            loadedReplies != null -> "Hide replies"
                                            else -> comment.repliesLabel
                                        },
                                        fontSize = 12.5.sp,
                                        fontWeight = FontWeight.SemiBold,
                                        color = accentColor,
                                        modifier = Modifier.clickable {
                                            if (isLoadingReply) return@clickable
                                            if (loadedReplies != null) {
                                                repliesMap.remove(comment.id)
                                            } else {
                                                loadingRepliesIds[comment.id] = true
                                                scope.launch {
                                                    val repRes = withContext(Dispatchers.IO) {
                                                        YouTube.commentsPage(comment.repliesToken, useWebClient)
                                                    }
                                                    repRes.onSuccess { repPage ->
                                                        repliesMap[comment.id] = repPage.comments
                                                    }
                                                    loadingRepliesIds[comment.id] = false
                                                }
                                            }
                                        }
                                    )
                                }

                                if (!loadedReplies.isNullOrEmpty()) {
                                    Spacer(modifier = Modifier.height(8.dp))
                                    Column(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .padding(start = 16.dp),
                                        verticalArrangement = Arrangement.spacedBy(8.dp)
                                    ) {
                                        loadedReplies.forEach { reply ->
                                            Surface(
                                                shape = RoundedCornerShape(12.dp),
                                                color = Color.White.copy(alpha = 0.05f),
                                                modifier = Modifier.fillMaxWidth()
                                            ) {
                                                Column(modifier = Modifier.padding(10.dp)) {
                                                    Text(
                                                        text = "${reply.author} · ${reply.publishedTime}",
                                                        fontSize = 11.5.sp,
                                                        fontWeight = FontWeight.SemiBold,
                                                        color = if (reply.isCreator) accentColor else Color.White.copy(alpha = 0.8f)
                                                    )
                                                    Spacer(modifier = Modifier.height(3.dp))
                                                    Text(
                                                        text = reply.text,
                                                        fontSize = 12.5.sp,
                                                        color = Color.White.copy(alpha = 0.88f)
                                                    )
                                                }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }

                    if (nextToken != null) {
                        item {
                            FilledTonalButton(
                                onClick = {
                                    if (isLoadingMore) return@FilledTonalButton
                                    val tok = nextToken ?: return@FilledTonalButton
                                    isLoadingMore = true
                                    scope.launch {
                                        val nextRes = withContext(Dispatchers.IO) {
                                            YouTube.commentsPage(tok, useWebClient)
                                        }
                                        nextRes.onSuccess { page ->
                                            val existingIds = comments.map { it.id }.toSet()
                                            comments = comments + page.comments.filterNot { it.id in existingIds }
                                            nextToken = page.nextToken
                                        }
                                        isLoadingMore = false
                                    }
                                },
                                modifier = Modifier.fillMaxWidth()
                            ) {
                                if (isLoadingMore) {
                                    LytrixExpressiveSpinner(color = accentColor, size = 20.dp, strokeWidth = 2.5.dp)
                                } else {
                                    Text("Load More Comments")
                                }
                            }
                        }
                    }

                    item { Spacer(modifier = Modifier.navigationBarsPadding().height(24.dp)) }
                }
            }
        }
    }
}

private fun cleanSearchQueryForMatch(rawTitle: String, rawArtist: String): String {
    val editRegex = Regex("""\b(edit|slowed|reverb|sped[ -]?up|speed[ -]?up|nightcore|remix|mashup|tiktok|audio\s+edit|edit\s+audio)\b""", RegexOption.IGNORE_CASE)
    val isEditOrRemix = editRegex.containsMatchIn(rawTitle) || editRegex.containsMatchIn(rawArtist)

    var title = rawTitle.replace(Regex("""\[.*?\]"""), " ")
    title = title.replace(Regex("""\(.*?(?:official|video|audio|lyric|slowed|reverb|speed|edit|remix|boost|bass|mashup|version|full|hd|4k|feat|ft|from|soundtrack|ost|theme).*?\)""", RegexOption.IGNORE_CASE), " ")
    title = title.replace(Regex("""\b(?:official\s+(?:music\s+)?video|music\s+video|lyric\s+video|full\s+video|video\s+song|slowed\s*(?:&|\+)?\s*reverb|edit\s+audio|bass\s+boosted)\b""", RegexOption.IGNORE_CASE), " ")
    title = title.replace(Regex("""[\u2018\u2019\u201C\u201D"']"""), " ")
    title = title.replace(Regex("""\s+[-–—~]\s+(?:from|soundtrack|ost|theme)\b.*$""", RegexOption.IGNORE_CASE), " ")

    val primaryArtist = rawArtist
        .split(Regex("""[,&/]|\bfeat\.?|\bft\.?""", RegexOption.IGNORE_CASE))
        .firstOrNull()?.trim() ?: rawArtist.trim()

    if (isEditOrRemix && primaryArtist.isNotBlank()) {
        title = title.replace(Regex("""\b${Regex.escape(primaryArtist)}\b""", RegexOption.IGNORE_CASE), " ")
    }

    title = title.replace(Regex("""\s+"""), " ").trim()
    if (title.isBlank()) title = rawTitle.trim()

    val isGeneric = primaryArtist.lowercase(java.util.Locale.ROOT) in listOf("unknown", "unknown artist", "various artists", "youtube video", "audio edit", "edit audio")
    return if (!isEditOrRemix && primaryArtist.isNotBlank() && !isGeneric && !title.contains(primaryArtist, ignoreCase = true)) {
        "$title $primaryArtist".trim()
    } else {
        title
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun YouTubeMatchOverrideDialog(
    song: Song,
    currentYouTubeId: String?,
    hasOverride: Boolean,
    accentColor: Color,
    onConfirm: (YouTubeMatchSelection) -> Unit,
    onResetOverride: () -> Unit,
    onDismiss: () -> Unit
) {
    val scope = rememberCoroutineScope()
    var modeTab by remember { mutableIntStateOf(0) } // 0 = Search, 1 = Paste URL / ID
    var searchQuery by remember(song.id) { mutableStateOf(cleanSearchQueryForMatch(song.title, song.artist)) }
    var filterVideos by remember { mutableStateOf(false) }
    var searchResults by remember { mutableStateOf<List<YouTubeMatchSelection>>(emptyList()) }
    var isSearching by remember { mutableStateOf(false) }

    var urlInput by remember { mutableStateOf("") }
    var urlPreview by remember { mutableStateOf<YouTubeMatchSelection?>(null) }
    var urlError by remember { mutableStateOf<String?>(null) }
    var isResolvingUrl by remember { mutableStateOf(false) }
    var keepOriginalMetadata by remember { mutableStateOf(true) }

    fun extractVideoId(input: String): String? {
        val trimmed = input.trim()
        if (trimmed.matches(Regex("^[a-zA-Z0-9_-]{11}$"))) return trimmed
        return try {
            val uri = Uri.parse(trimmed)
            when {
                uri.host?.contains("youtu.be") == true -> uri.pathSegments.firstOrNull()
                uri.host?.contains("youtube.com") == true -> uri.getQueryParameter("v")
                    ?: uri.pathSegments.takeIf { it.size >= 2 && it[0] == "shorts" }?.getOrNull(1)
                else -> null
            }?.takeIf { it.matches(Regex("^[a-zA-Z0-9_-]{11}$")) }
        } catch (_: Exception) {
            null
        }
    }

    fun runSearch(q: String, asVideos: Boolean) {
        if (q.isBlank()) return
        scope.launch {
            isSearching = true
            val filter = if (asVideos) YouTube.SearchFilter.FILTER_VIDEO else YouTube.SearchFilter.FILTER_SONG
            val res = withContext(Dispatchers.IO) { YouTube.search(q.trim(), filter) }
            val items = res.getOrNull()?.items.orEmpty().mapNotNull { item ->
                when (item) {
                    is SongItem -> YouTubeMatchSelection(
                        videoId = item.id,
                        title = item.title,
                        artist = item.artists.joinToString(", ") { it.name },
                        thumbnailUrl = item.thumbnail,
                        durationSec = item.duration,
                        isVideo = false
                    )
                    is VideoItem -> YouTubeMatchSelection(
                        videoId = item.id,
                        title = item.title,
                        artist = item.authors.orEmpty().joinToString(", ") { it.name }.ifBlank { "YouTube Video" },
                        thumbnailUrl = item.thumbnail,
                        durationSec = item.duration,
                        isVideo = true
                    )
                    else -> null
                }
            }
            searchResults = items
            isSearching = false
        }
    }

    LaunchedEffect(modeTab, filterVideos) {
        if (modeTab == 0) {
            runSearch(searchQuery, filterVideos)
        }
    }

    LaunchedEffect(urlInput) {
        val id = extractVideoId(urlInput)
        if (id == null) {
            urlPreview = null
            urlError = null
            return@LaunchedEffect
        }
        isResolvingUrl = true
        urlError = null
        val item = withContext(Dispatchers.IO) {
            YouTube.queue(listOf(id)).getOrNull()?.firstOrNull()
        }
        isResolvingUrl = false
        if (item != null) {
            urlPreview = YouTubeMatchSelection(
                videoId = item.id,
                title = item.title,
                artist = item.artists.joinToString(", ") { it.name },
                thumbnailUrl = item.thumbnail,
                durationSec = item.duration,
                isVideo = filterVideos
            )
        } else {
            urlPreview = null
            urlError = "Could not load track details for \"$id\""
        }
    }

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = Modifier
                .fillMaxWidth(0.94f)
                .fillMaxHeight(0.84f),
            shape = RoundedCornerShape(24.dp),
            color = MaterialTheme.colorScheme.surfaceContainerLow
        ) {
            Column(modifier = Modifier.fillMaxSize().padding(18.dp)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text("Change YouTube Match", fontSize = 18.sp, fontWeight = FontWeight.Bold)
                        Text(
                            text = if (!currentYouTubeId.isNullOrBlank()) {
                                "Stream ID: $currentYouTubeId · Replaces audio source without changing song title"
                            } else {
                                "Swap audio/video version without replacing the song"
                            },
                            fontSize = 11.sp,
                            color = accentColor,
                            maxLines = 2
                        )
                    }
                    if (hasOverride) {
                        TextButton(onClick = { onResetOverride(); onDismiss() }) {
                            Text("Reset", color = MaterialTheme.colorScheme.error)
                        }
                    }
                    IconButton(onClick = onDismiss) {
                        Icon(Icons.Rounded.Close, contentDescription = "Close")
                    }
                }

                Spacer(modifier = Modifier.height(8.dp))

                Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
                    FilterChip(
                        selected = modeTab == 0,
                        onClick = { modeTab = 0 },
                        label = { Text("Search Match") },
                        modifier = Modifier.weight(1f)
                    )
                    FilterChip(
                        selected = modeTab == 1,
                        onClick = { modeTab = 1 },
                        label = { Text("Paste URL / ID") },
                        modifier = Modifier.weight(1f)
                    )
                }

                Spacer(modifier = Modifier.height(8.dp))

                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = MaterialTheme.colorScheme.surfaceContainerHigh,
                    modifier = Modifier
                        .fillMaxWidth()
                        .clickable { keepOriginalMetadata = !keepOriginalMetadata }
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(
                                text = "Keep original song title & cover",
                                fontSize = 13.sp,
                                fontWeight = FontWeight.Medium
                            )
                            Text(
                                text = if (keepOriginalMetadata) "Only stream changes; keeps current title & artwork" else "Replaces song title, artist & cover with matched version",
                                fontSize = 11.sp,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                maxLines = 1,
                                overflow = TextOverflow.Ellipsis
                            )
                        }
                        Switch(
                            checked = keepOriginalMetadata,
                            onCheckedChange = { keepOriginalMetadata = it },
                            colors = SwitchDefaults.colors(checkedTrackColor = accentColor)
                        )
                    }
                }

                Spacer(modifier = Modifier.height(10.dp))

                if (modeTab == 0) {
                    OutlinedTextField(
                        value = searchQuery,
                        onValueChange = { searchQuery = it },
                        singleLine = true,
                        label = { Text("Search YouTube Music") },
                        trailingIcon = {
                            IconButton(onClick = { runSearch(searchQuery, filterVideos) }) {
                                Icon(Icons.Rounded.Search, contentDescription = "Search")
                            }
                        },
                        shape = RoundedCornerShape(14.dp),
                        modifier = Modifier.fillMaxWidth()
                    )

                    Spacer(modifier = Modifier.height(8.dp))
                    Row(
                        horizontalArrangement = Arrangement.spacedBy(8.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        FilterChip(
                            selected = !filterVideos,
                            onClick = { filterVideos = false },
                            label = { Text("Official Songs", maxLines = 1) }
                        )
                        FilterChip(
                            selected = filterVideos,
                            onClick = { filterVideos = true },
                            label = { Text("Music Videos", maxLines = 1) }
                        )
                    }

                    Spacer(modifier = Modifier.height(8.dp))
                    if (isSearching) {
                        Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                            LytrixExpressiveSpinner(color = accentColor, size = 38.dp)
                        }
                    } else {
                        LazyColumn(
                            modifier = Modifier.weight(1f),
                            verticalArrangement = Arrangement.spacedBy(8.dp)
                        ) {
                            items(searchResults, key = { it.videoId }) { candidate ->
                                val isCurrent = candidate.videoId == currentYouTubeId
                                MatchCandidateCard(
                                    candidate = candidate,
                                    isCurrent = isCurrent,
                                    accentColor = accentColor,
                                    onClick = {
                                        if (!isCurrent) {
                                            onConfirm(candidate.copy(keepOriginalMetadata = keepOriginalMetadata))
                                            onDismiss()
                                        }
                                    }
                                )
                            }
                        }
                    }
                } else {
                    OutlinedTextField(
                        value = urlInput,
                        onValueChange = { urlInput = it },
                        singleLine = true,
                        label = { Text("Paste YouTube URL or 11-char ID") },
                        placeholder = { Text("https://youtu.be/...") },
                        shape = RoundedCornerShape(14.dp),
                        modifier = Modifier.fillMaxWidth()
                    )

                    Spacer(modifier = Modifier.height(14.dp))
                    when {
                        isResolvingUrl -> Box(
                            modifier = Modifier.fillMaxWidth().padding(vertical = 12.dp),
                            contentAlignment = Alignment.Center
                        ) {
                            LytrixExpressiveSpinner(color = accentColor, size = 32.dp)
                        }
                        urlError != null -> Text(urlError!!, color = MaterialTheme.colorScheme.error, fontSize = 13.sp)
                        urlPreview != null -> {
                            val item = urlPreview!!
                            val isCurrent = item.videoId == currentYouTubeId
                            MatchCandidateCard(
                                candidate = item,
                                isCurrent = isCurrent,
                                accentColor = accentColor,
                                onClick = {
                                    if (!isCurrent) {
                                        onConfirm(item.copy(keepOriginalMetadata = keepOriginalMetadata))
                                        onDismiss()
                                    }
                                }
                            )
                            Spacer(modifier = Modifier.height(12.dp))
                            Button(
                                onClick = {
                                    onConfirm(item.copy(keepOriginalMetadata = keepOriginalMetadata))
                                    onDismiss()
                                },
                                enabled = !isCurrent,
                                colors = ButtonDefaults.buttonColors(containerColor = accentColor),
                                modifier = Modifier.fillMaxWidth()
                            ) {
                                Text(if (isCurrent) "Already Playing This Match" else "Apply Match")
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun MatchCandidateCard(
    candidate: YouTubeMatchSelection,
    isCurrent: Boolean,
    accentColor: Color,
    onClick: () -> Unit
) {
    Surface(
        shape = RoundedCornerShape(14.dp),
        color = if (isCurrent) accentColor.copy(alpha = 0.16f) else MaterialTheme.colorScheme.surfaceContainerHigh,
        modifier = Modifier
            .fillMaxWidth()
            .border(
                width = if (isCurrent) 1.5.dp else 0.dp,
                color = if (isCurrent) accentColor else Color.Transparent,
                shape = RoundedCornerShape(14.dp)
            )
            .clickable(onClick = onClick)
    ) {
        Row(
            modifier = Modifier.padding(10.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            AsyncImage(
                model = candidate.thumbnailUrl,
                contentDescription = candidate.title,
                contentScale = ContentScale.Crop,
                modifier = Modifier
                    .size(50.dp)
                    .clip(RoundedCornerShape(10.dp))
            )
            Spacer(modifier = Modifier.width(12.dp))
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = candidate.title,
                    fontWeight = FontWeight.SemiBold,
                    fontSize = 14.sp,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
                Text(
                    text = candidate.artist,
                    fontSize = 12.sp,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
                val durText = candidate.durationSec?.takeIf { it > 0 }?.let { sec ->
                    String.format(" · %d:%02d", sec / 60, sec % 60)
                }.orEmpty()
                Text(
                    text = (if (isCurrent) "Active match" else candidate.videoId) + durText,
                    fontSize = 11.sp,
                    color = if (isCurrent) accentColor else MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f)
                )
            }
        }
    }
}

@Composable
fun CustomCoverEditDialog(
    song: Song,
    hasCustomCover: Boolean,
    accentColor: Color,
    onPickImageUri: (Uri) -> Unit,
    onApplyImageUrl: (String) -> Unit,
    onRemoveCustomCover: () -> Unit,
    onDismiss: () -> Unit
) {
    var imageUrlText by remember { mutableStateOf("") }
    val photoPicker = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.PickVisualMedia()
    ) { uri ->
        if (uri != null) {
            onPickImageUri(uri)
            onDismiss()
        }
    }

    Dialog(onDismissRequest = onDismiss) {
        Surface(
            shape = RoundedCornerShape(24.dp),
            color = MaterialTheme.colorScheme.surfaceContainerLow,
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(22.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                Text("Custom Cover Art", fontSize = 19.sp, fontWeight = FontWeight.Bold)
                Text(
                    text = song.title,
                    fontSize = 12.5.sp,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )

                Button(
                    onClick = {
                        photoPicker.launch(
                            PickVisualMediaRequest(ActivityResultContracts.PickVisualMedia.ImageOnly)
                        )
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = accentColor),
                    shape = RoundedCornerShape(14.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Icon(Icons.Rounded.PhotoLibrary, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text("Choose Image from Gallery")
                }

                OutlinedTextField(
                    value = imageUrlText,
                    onValueChange = { imageUrlText = it },
                    label = { Text("Or paste image URL (https://...)") },
                    singleLine = true,
                    shape = RoundedCornerShape(14.dp),
                    modifier = Modifier.fillMaxWidth()
                )

                if (imageUrlText.trim().startsWith("http")) {
                    FilledTonalButton(
                        onClick = {
                            onApplyImageUrl(imageUrlText.trim())
                            onDismiss()
                        },
                        shape = RoundedCornerShape(14.dp),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Text("Apply Cover URL")
                    }
                }

                if (hasCustomCover) {
                    OutlinedButton(
                        onClick = {
                            onRemoveCustomCover()
                            onDismiss()
                        },
                        shape = RoundedCornerShape(14.dp),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Icon(
                            imageVector = Icons.Rounded.RestartAlt,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.error,
                            modifier = Modifier.size(18.dp)
                        )
                        Spacer(modifier = Modifier.width(6.dp))
                        Text("Restore Original Cover", color = MaterialTheme.colorScheme.error)
                    }
                }

                TextButton(
                    onClick = onDismiss,
                    modifier = Modifier.align(Alignment.End)
                ) {
                    Text("Cancel")
                }
            }
        }
    }
}
