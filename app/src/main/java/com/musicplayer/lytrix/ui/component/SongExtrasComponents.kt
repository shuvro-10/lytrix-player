data class CreditEntry(
    val role: String,
    val value: String
)

object SongCreditsParser {
    private val KNOWN_ROLE_PREFIXES = listOf(
        "Provided to YouTube by" to "Distributor / Label",
        "Released on" to "Release Date",
        "Music Publisher" to "Publisher",
        "Associated Performer" to "Performer",
        "Mastering Engineer" to "Mastering Engineer",
        "Mixing Engineer" to "Mixing Engineer",
        "Recording Engineer" to "Recording Engineer",
        "Vocals" to "Vocals",
        "Producer" to "Producer",
        "Composer" to "Composer",
        "Lyricist" to "Lyricist",
        "Writer" to "Writer",
        "Arranger" to "Arranger",
        "Author" to "Author",
        "Featured Artist" to "Featured Artist",
        "Main Artist" to "Main Artist",
        "Auto-generated by YouTube" to "Source"
    )

    fun parseFromDescription(description: String?): List<CreditEntry> {
        if (description.isNullOrBlank()) return emptyList()
        val credits = mutableListOf<CreditEntry>()
        val seen = HashSet<String>()

        for (rawLine in description.lines()) {
            val line = rawLine.trim()
            if (line.isBlank()) continue

            if (line.startsWith("Provided to YouTube by", ignoreCase = true)) {
                val valText = line.substringAfter("by", "").trim().ifBlank { line }
                val key = "label::$valText"
                if (seen.add(key)) credits.add(CreditEntry("Provided To YouTube By", valText))
                continue
            }

            if (line.startsWith("℗") || line.startsWith("©")) {
                if (seen.add("cp::$line")) credits.add(CreditEntry("Copyright", line))
                continue
            }

            if (line.equals("Auto-generated by YouTube.", ignoreCase = true)) {
                if (seen.add("src::autogen")) credits.add(CreditEntry("Source", "YouTube Music Auto-Generated"))
                continue
            }

            val colonIdx = line.indexOf(':')
            if (colonIdx in 2..36) {
                val left = line.substring(0, colonIdx).trim()
                val right = line.substring(colonIdx + 1).trim()
                if (right.isNotBlank() && !left.startsWith("http", ignoreCase = true)) {
                    val matched = KNOWN_ROLE_PREFIXES.firstOrNull { (prefix, _) ->
                        left.equals(prefix, ignoreCase = true) || left.contains(prefix, ignoreCase = true)
                    }
                    if (matched != null) {
                        val key = "${matched.second}::$right"
                        if (seen.add(key)) credits.add(CreditEntry(left, right))
                    }
                }
            }
        }
        return credits
    }
}

